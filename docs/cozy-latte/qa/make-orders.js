/* Builds docs/cozy-latte/orders.js — the order shapes.
   Each shape (except the plain circle) is what THIS fluid actually produces from a fixed hand movement (qa/gestures.js),
   mirrored left-right and smoothed. So every order is makeable by construction; the robot re-pours them to prove it. */
const { chromium } = require(process.env.PW || '/opt/node22/lib/node_modules/playwright');
const fs = require('fs'), path = require('path');
const G = require('./gestures.js');
const BASE = process.argv[2] || 'http://localhost:8765/cozy-latte/';
const MS = 96, RD = 0.48;
const inDisc = (x, y) => { const a = (x + 0.5) / MS - 0.5, b = (y + 0.5) / MS - 0.5; return a * a + b * b <= RD * RD; };
function smooth(bits, passes, close) {
  let a = Float32Array.from(bits);
  const box = src => { const o = new Float32Array(MS * MS); for (let y = 0; y < MS; y++) for (let x = 0; x < MS; x++) { let s = 0, n = 0; for (let j = -1; j <= 1; j++) for (let i = -1; i <= 1; i++) { const X = x + i, Y = y + j; if (X >= 0 && X < MS && Y >= 0 && Y < MS) { s += src[Y * MS + X]; n++; } } o[y * MS + x] = s / n; } return o; };
  const morph = (src, grow) => { const o = new Float32Array(MS * MS); for (let y = 0; y < MS; y++) for (let x = 0; x < MS; x++) { let v = grow ? 0 : 1; for (let j = -1; j <= 1; j++) for (let i = -1; i <= 1; i++) { const X = Math.min(MS - 1, Math.max(0, x + i)), Y = Math.min(MS - 1, Math.max(0, y + j)); v = grow ? Math.max(v, src[Y * MS + X]) : Math.min(v, src[Y * MS + X]); } o[y * MS + x] = v; } return o; };
  for (let k = 0; k < close; k++) a = morph(a, true); for (let k = 0; k < close; k++) a = morph(a, false);     // close thin coffee lines
  const m = new Float32Array(MS * MS); for (let y = 0; y < MS; y++) for (let x = 0; x < MS; x++) m[y * MS + x] = (a[y * MS + x] + a[y * MS + (MS - 1 - x)]) / 2;   // mirror
  a = m; for (let k = 0; k < passes; k++) a = box(a);
  return Uint8Array.from(a, (v, i) => (v >= 0.5 && inDisc(i % MS, Math.floor(i / MS)) ? 1 : 0));
}
const pack = bits => { const b = Buffer.alloc(MS * MS / 8); for (let i = 0; i < bits.length; i++) if (bits[i]) b[i >> 3] |= 128 >> (i & 7); return b.toString('base64'); };
(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const pour = async name => { const ctx = await browser.newContext({ viewport: { width: 320, height: 568 } }); const p = await ctx.newPage();
    await p.addInitScript(() => localStorage.setItem('cozy-latte.demo.v1', '1'));
    await p.goto(BASE + '?manual=1&mode=free&level=2'); await p.waitForTimeout(600);
    await p.evaluate('(function(){' + G.RUN_SRC + '; return runGesture(' + JSON.stringify(G.GESTURES[name]) + ')})()');
    const m = await p.evaluate(() => __latte.mask()); await ctx.close(); return Uint8Array.from(m, c => +c); };
  const [heart, leaf] = await Promise.all([pour('heart'), pour('leaf')]);
  const circle = new Uint8Array(MS * MS); for (let y = 0; y < MS; y++) for (let x = 0; x < MS; x++) { const a = (x + 0.5) / MS - 0.5, b = (y + 0.5) / MS - 0.5; if (Math.hypot(a, b) <= RD * 0.68) circle[y * MS + x] = 1; }
  const orders = [
    { id: 'circle', name: 'Circle', bits: circle },
    { id: 'heart', name: 'Heart', bits: smooth(heart, 2, 1) },
    { id: 'leaf', name: 'Leaf', bits: smooth(leaf, 1, 2) },
  ];
  const js = '/* Generated by qa/make-orders.js — do not edit by hand. Order shapes, ' + MS + '×' + MS + ' cells, 1 bit each, bottom row first. */\n' +
    'window.LATTE_ORDERS=' + JSON.stringify(orders.map(o => ({ id: o.id, name: o.name, n: MS, b64: pack(o.bits) }))) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'orders.js'), js);
  for (const o of orders) { let s = ''; for (let y = MS - 1; y >= 0; y -= 3) { for (let x = 0; x < MS; x += 2) s += o.bits[y * MS + x] ? '#' : (inDisc(x, y) ? '.' : ' '); s += '\n'; } console.log(o.id, [...o.bits].reduce((a, b) => a + b, 0), 'cells\n' + s); }
  await browser.close();
})();
